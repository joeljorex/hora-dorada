export const ANCHO = 26;
export const ALTO = 15;

// Devuelve el mapa completo (26×15) con borde de muro.
export function mapaCompleto(def) {
  const filas = ['#'.repeat(ANCHO)];
  for (const f of def.mapa) {
    if (f.length !== ANCHO - 2) console.warn(`Nivel "${def.nombre}": fila de ${f.length} columnas`, f);
    filas.push('#' + f.padEnd(ANCHO - 2, '.').slice(0, ANCHO - 2) + '#');
  }
  while (filas.length < ALTO - 1) filas.push('#' + '.'.repeat(ANCHO - 2) + '#');
  filas.push('#'.repeat(ANCHO));
  return filas;
}
